import { afterAll, expect, test } from 'vitest';
import { assessTraining } from '../src/shared/adaptation';
import { prisma } from '../src/shared/lib/prisma';
import { getPlan } from '../src/server/plan';
import { saveTodayChoice, saveWeekReview } from '../src/server/adaptation';
import { createTraining, trainingAction } from '../src/server/training';
const prefix = `adapt-v2-${Date.now()}`;
afterAll(async () => { await prisma.user.deleteMany({ where: { id: { startsWith: prefix } } }); await prisma.$disconnect(); });
const good = { pct: 100, technique: 'good', difficulty: 'too_easy' };
const input = { baseStep: 3, planned: 3, screened: false, sessions: [good, good, good] };
test('increase needs enough actual completions, explicit form and recovery; one bounded step', () => {
  expect(assessTraining(input)).toMatchObject({ step: 4, change: 'up' });
  expect(assessTraining({ ...input, sessions: [good] }).step).toBe(3);
  expect(assessTraining({ ...input, sessions: [good, good, { pct: 100 }] }).step).toBe(4);
  expect(assessTraining({ ...input, sessions: [{ pct: 100, difficulty: 'too_easy' }, { pct: 100, difficulty: 'too_easy' }, { pct: 100 }] }).step).toBe(3);
  for (const extra of [{ readinessLow: true }, { daysAway: 8 }, { sessions: [good, { ...good, pain: true }] }, { sessions: [good, { ...good, technique: 'needs_work' }] }]) expect(assessTraining({ ...input, ...extra }).step).toBe(2);
  expect(assessTraining({ ...input, fuelLow: true }).step).toBe(3);
  expect(assessTraining({ ...input, waterLow: true }).step).toBe(3);
  expect(assessTraining({ ...input, screened: true }).step).toBe(3);
  expect(assessTraining({ ...input, sessions: [{ pct: 20, stopReason: 'later' }] }).step).toBe(3);
  expect(assessTraining({ ...input, sessions: [{ pct: 20 }] }).step).toBe(2);
});
test('plan reads never compound; weekly close advances once, is owner isolated and rejects injected identity', async () => {
  const a = prefix + 'a', b = prefix + 'b';
  for (const id of [a,b]) await prisma.user.create({ data: { id, email: `${id}@example.test`, name: 'Synthetic', profile: { create: { onboarded: true, intakeVersion: 1, equipment: ['body weight'], daysPerWeek: 3, planStep: 3 } } } });
  await getPlan(a, 'home');
  const session = await createTraining(a, 'free', { name: 'Test', program: { key: 'personal', day: 1 }, exercises: [{ exerciseId: 'dataset-0294', sets: 1, reps: 10, restSeconds: 30, targetKg: 0 }] });
  await prisma.workoutSession.update({ where: { id: session.id }, data: { status: 'completed', endedAt: new Date(), completionPct: 30, note: 'quit:too_hard' } });
  expect((await getPlan(a,'home')).step).toBe(2);
  expect((await getPlan(a,'home')).step).toBe(2);
  expect((await getPlan(b,'home')).step).toBe(3);
  await expect(saveTodayChoice(a, { minutes: 10, lighter: true, userId: b })).rejects.toThrow();
  await saveTodayChoice(a, { minutes: 10, lighter: true });
  expect((await getPlan(a,'home')).adaptive.todayChoice?.minutes).toBe(10);
  expect((await getPlan(b,'home')).adaptive.todayChoice).toBeNull();
  const check = { expectedWeek: 1, finishWeek: true, energy: 3, sleep: 3, soreness: 2, preference: 'same', minutes: 20 };
  await saveWeekReview(a, check); await saveWeekReview(a, check);
  expect((await prisma.fitnessProfile.findUniqueOrThrow({ where: { userId: a } })).planWeek).toBe(2);
  expect((await prisma.fitnessProfile.findUniqueOrThrow({ where: { userId: b } })).planWeek).toBe(1);
  const stopped = await createTraining(b, 'free', { name: 'Pain before first set', exercises: [{ exerciseId: 'dataset-0294', sets: 1, reps: 10, restSeconds: 30, targetKg: 0 }] });
  await trainingAction(b, stopped.id, { actionId: 'pain-stop-test', revision: 0, kind: 'abandon', confirm: true, reason: 'pain' });
  const pain = await getPlan(b, 'home');
  expect(pain.adaptive.decision.reasons).toContain('pain');
  expect(pain.adaptive.decision.completed).toBe(0);
  expect(pain.step).toBe(2);
});
