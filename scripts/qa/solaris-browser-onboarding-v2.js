async page => {
  const origin = new URL(page.url());
  if (origin.hostname !== '127.0.0.1' && !origin.hostname.endsWith('.w.modal.host')) throw new Error('Disposable test preview only');
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.context().clearCookies();
  await page.evaluate(async () => { for (const r of await navigator.serviceWorker.getRegistrations()) await r.unregister(); for (const k of await caches.keys()) await caches.delete(k); });
  await page.evaluate(() => { localStorage.setItem('mingalar-locale', 'en'); localStorage.setItem('mingalar-theme', 'light'); });
  await page.reload(); await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.getByRole('button', { name: 'Create account', exact: true }).first().click();
  await page.getByRole('textbox', { name: 'Your name', exact: true }).fill('Mya');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill(`solaris-${Date.now()}@example.test`);
  await page.getByRole('textbox', { name: 'Password At least 10 characters', exact: true }).fill('Synthetic-solaris-review-2026');
  await page.locator('form').getByRole('button', { name: 'Create account', exact: true }).click();
  await page.locator('.quiz').waitFor();
  const checks = [];
  const capture = async name => {
    await page.waitForTimeout(200);
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth);
    if (overflow > 0) throw new Error(`${name}: overflow ${overflow}`);
    await page.screenshot({ path: `evidence/solaris-onboarding-${name}.png`, fullPage: true });
    checks.push({ name, overflow });
  };
  const next = async () => { await page.locator('.quiz-next').click(); await page.waitForTimeout(150); };
  const pick = async label => { await page.locator('.quiz-option').filter({ hasText: label }).first().click(); await page.waitForTimeout(150); };
  await capture('welcome-en-390'); await next();
  await page.locator('.quiz-text').fill('Mya'); await next(); await pick('Lose weight');
  await page.locator('.focus-choice').filter({ hasText: 'Waist & core' }).click();
  await page.locator('.focus-choice').filter({ hasText: 'Glutes' }).click();
  await capture('focus-en-390'); await next();
  await page.locator('.current-shape').nth(2).click(); await page.locator('.shape-option').first().click();
  await capture('waist-en-390');
  await page.getByRole('button', { name: 'Language', exact: true }).click();
  await page.setViewportSize({ width: 320, height: 740 }); await capture('waist-my-320');
  await page.getByRole('button', { name: 'Language', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 }); await next();
  await page.locator('.current-shape').first().click(); await page.locator('.shape-option').first().click();
  await page.locator('.goal-measurements summary').click();
  await page.getByLabel('Waist now (cm)').fill('80'); await page.getByLabel('Hips now (cm)').fill('95');
  await capture('glutes-en-390'); await next();
  await pick('Prefer not to say'); await page.locator('.quiz-option').nth(2).click();
  await next(); await next(); await next(); await pick('Some walking'); await pick('At home');
  await pick('Dumbbell'); await capture('equipment-en-390'); await next();
  await pick('New to training'); await next(); await pick('Evening'); await pick('20 min'); await next();
  await pick('No'); await next(); await page.locator('.quiz[data-step=review]').waitFor(); await capture('review-en-390');
  await page.locator('.review-row').filter({ hasText: 'How tall are you?' }).getByRole('button', { name: 'Edit', exact: true }).click();
  await page.locator('.quiz-stepper button').last().click(); await next();
  if (!await page.locator('.quiz-review').innerText().then(t => t.includes('166 cm'))) throw new Error('Review edit did not persist');
  await next(); await page.locator('.plan-view').waitFor({ timeout: 60000 });
  const prefs = await page.request.get(new URL('/api/training/prefs', page.url()).href).then(r => r.json());
  if (prefs.bodyPreferences.currentWaist !== 'fuller' || prefs.bodyPreferences.currentGlutes !== 'small' || prefs.bodyPreferences.gluteGoal !== 'build' || prefs.bodyPreferences.waistCm !== 80) throw new Error('Preferences not saved');
  await page.reload(); await page.locator('.plan-view').waitFor(); await page.waitForTimeout(1500); await capture('completed-home-en-390');
  return { result: errors.length ? 'FAIL' : 'PASS', pageErrors: errors, checks, savedBodyPreferences: prefs.bodyPreferences, reviewEdit: true, reload: true };
}
