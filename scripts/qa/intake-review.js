async page => {
  const origin=new URL(page.url()).origin;
  if(!new URL(origin).hostname.endsWith('.w.modal.host'))throw new Error('Disposable preview only');
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const post=async(path,data)=>{const r=await page.request.post(origin+path,{data,headers:{Origin:origin}});if(!r.ok())throw new Error(path+': '+r.status());return r.json();};
  await post('/api/auth/sign-up/email',{name:'Intake Preview',email:`intake-${Date.now()}@example.test`,password:'Disposable-preview-2026-only'});
  await page.evaluate(()=>{localStorage.setItem('mingalar-locale','en');localStorage.setItem('mingalar-theme','light');});
  await page.setViewportSize({width:390,height:900});await page.reload();await page.locator('.intake-v2').waitFor();
  const next=()=>page.locator('.quiz-next').click();
  const picker=()=>page.getByRole('slider');
  const at=async step=>{await page.locator(`.intake-v2[data-step="${step}"]`).waitFor();if(await page.locator('.intake-v2 input[type=number]').count())throw new Error('Typing still required');};
  await at('age');await picker().focus();await picker().press('ArrowDown');
  if(await picker().getAttribute('aria-valuenow')!=='31')throw new Error('Age keyboard failed');
  await picker().hover();await page.mouse.wheel(0,192);await page.waitForTimeout(600);
  const age=Number(await picker().getAttribute('aria-valuenow'));if(age<=31)throw new Error('Vertical age scrolling failed');
  await page.screenshot({path:'D:/workout_fitness/evidence/intake-release/age-wheel.png'});
  await next();await at('height');await picker().focus();for(let i=0;i<5;i++)await picker().press('ArrowRight');
  if(await picker().getAttribute('aria-valuenow')!=='170')throw new Error('Height ruler failed');
  await page.screenshot({path:'D:/workout_fitness/evidence/intake-release/height-ruler.png'});
  await next();await at('weight');await picker().focus();for(let i=0;i<10;i++)await picker().press('ArrowRight');
  if(await picker().getAttribute('aria-valuenow')!=='70')throw new Error('Weight ruler failed');
  await next();await at('sex');await page.getByRole('button',{name:'Prefer not to say',exact:true}).click();
  await next();await at('goal');await page.locator('.quiz-grid .quiz-option').nth(3).click();
  await next();await at('level');await page.locator('.quiz-grid .quiz-option').nth(1).click();
  await next();await at('activity');await page.locator('.quiz-grid .quiz-option').nth(2).click();
  await next();await at('place');await page.locator('.quiz-grid .quiz-option').nth(0).click();
  await next();await at('days');await page.locator('.quiz-grid button').nth(1).click();
  await next();await at('minutes');await page.locator('.quiz-grid button').nth(0).click();
  await next();await at('health');await page.getByLabel('None of these',{exact:true}).check();
  await next();await at('focus');await page.locator('.focus-choice').nth(2).click();
  await page.screenshot({path:'D:/workout_fitness/evidence/intake-release/focus-en.png',fullPage:true});
  await next();await at('waistNow');await page.locator('.intake-shape').nth(1).click();
  await next();await at('waistGoal');await page.locator('.intake-shape').nth(1).click();
  await next();await at('glutesNow');await page.locator('.intake-shape').nth(0).click();
  await next();await at('glutesGoal');await page.locator('.intake-shape').nth(0).click();
  await page.screenshot({path:'D:/workout_fitness/evidence/intake-release/glute-goal.png',fullPage:true});
  await next();await at('review');if(!(await page.locator('.intake-review').innerText()).includes('170 cm'))throw new Error('Missing review data');
  await page.screenshot({path:'D:/workout_fitness/evidence/intake-release/review-en.png',fullPage:true});
  await next();await page.locator('.home-v2').waitFor({timeout:30000});
  const boot=await page.request.get(origin+'/api/fitness/bootstrap').then(r=>r.json());
  if(boot.profile.intakeVersion!==1||boot.profile.heightCm!==170||boot.measurements[0].weightKg!==70||new Date().getUTCFullYear()-boot.profile.birthYear!==age)throw new Error('Intake did not persist');
  await page.locator('.mobile-nav button').nth(1).click();await page.locator('.media-grid .media-card').first().waitFor();
  const home=await page.locator('.media-grid .media-card').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('data-exercise')));
  if(home.length!==19||home.includes('core-165'))throw new Error('Wrong Home collection');
  await page.screenshot({path:'D:/workout_fitness/evidence/intake-release/home-collection.png',fullPage:true});
  await page.locator('.discover-view .seg-switch').first().locator('button').nth(1).click();
  const gym=await page.locator('.media-grid .media-card').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('data-exercise')));
  if(!gym.length||gym.some(id=>home.includes(id)))throw new Error('Gym collection overlaps Home');
  await page.screenshot({path:'D:/workout_fitness/evidence/intake-release/gym-collection.png',fullPage:true});
  await page.locator('.mobile-nav button').nth(0).click();await page.locator('.hv-banner').nth(1).click();await page.locator('.wi-exercises li').first().waitFor();
  const start=page.locator('.wi-footer button');
  const button=await start.evaluate(e=>({color:getComputedStyle(e).backgroundColor,height:e.getBoundingClientRect().height}));
  const rgb=button.color.match(/[\d.]+/g).map(Number);
  if(rgb[0]<170||rgb[1]>70||rgb[2]>70||button.height<60)throw new Error('Start is not big and red: '+JSON.stringify(button));
  await page.screenshot({path:'D:/workout_fitness/evidence/intake-release/workout-intro.png',fullPage:true});
  await start.click();await page.locator('.minimal-player.phase-ready').waitFor({timeout:30000});
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  return {result:'PASS',intakeVersion:boot.profile.intakeVersion,heightCm:boot.profile.heightCm,weightKg:boot.measurements[0].weightKg,homeIds:home,gymIds:gym,start:button,errors};
}
